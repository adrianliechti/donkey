func serverInitCommand() *cli.Command {
	return &cli.Command{
		Name:  "init",
		Usage: "print a concise control-plane settings file",
		Flags: []cli.Flag{
			&cli.StringFlag{Name: "runtime", Value: "kubernetes", Usage: "settings to generate: kubernetes or docker"},
		},
		Action: func(_ context.Context, cmd *cli.Command) error {
			template, err := serverInitTemplate(cmd.String("runtime"))
			if err != nil {
				return err
			}
			_, err = fmt.Fprint(cmd.Root().Writer, template)
			return err
		},
	}
}

func serverInitTemplate(runtimeName string) (string, error) {
	switch runtimeName {
	case "", "kubernetes":
		return kubernetesInstallTemplate, nil
	case "docker":
		return dockerInstallTemplate, nil
	default:
		return "", fmt.Errorf("runtime must be kubernetes or docker, not %q", runtimeName)
	}
}

func serverRenderCommand() *cli.Command {
	flags := serverSettingsFlags()
	flags = append(flags,
		&cli.StringFlag{Name: "output", Aliases: []string{"o"}, Usage: "directory to write the deployment bundle"},
		&cli.BoolFlag{Name: "force", Usage: "replace files in the output directory which donkey generates"},
	)
	return &cli.Command{
		Name:  "render",
		Usage: "render Kubernetes or Docker Compose deployment files without applying them",
		Flags: flags,
		Action: func(_ context.Context, cmd *cli.Command) error {
			output := cmd.String("output")
			if output == "" {
				return fmt.Errorf("--output is required (for example: --output deploy)")
			}
			settings, err := loadInstallSettings(cmd, false)
			if err != nil {
				return err
			}
			var files map[string]bundleFile
			runtimeName := settings.Runtime
			if runtimeName == "" {
				runtimeName = "kubernetes"
			}
			switch runtimeName {
			case "kubernetes":
				files, err = renderKubernetesBundle(settings)
			case "docker":
				files, err = renderDockerBundle(settings)
			default:
				return fmt.Errorf("runtime must be kubernetes or docker, not %q", settings.Runtime)
			}
			if err != nil {
				return err
			}
			if err := writeServerBundle(output, files, cmd.Bool("force")); err != nil {
				return err
			}
			_, err = fmt.Fprintf(cmd.Root().Writer, "Rendered %s deployment bundle in %s\n", runtimeName, filepath.Clean(output))
			return err
		},
	}
}

type bundleFile struct {
	Data []byte
	Mode os.FileMode
}

func writeServerBundle(output string, files map[string]bundleFile, force bool) error {
	output = filepath.Clean(output)
	if info, err := os.Stat(output); err == nil && !info.IsDir() {
		return fmt.Errorf("output %s is not a directory", output)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	for name := range files {
		if filepath.Base(name) != name || name == "." {
			return fmt.Errorf("invalid generated file name %q", name)
		}
		target := filepath.Join(output, name)
		if info, err := os.Lstat(target); err == nil {
			if info.IsDir() {
				return fmt.Errorf("%s is a directory; expected a generated file", target)
			}
			if !force {
				return fmt.Errorf("%s already exists; use --force to replace generated files", target)
			}
		} else if err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	if err := os.MkdirAll(output, 0o755); err != nil {
		return err
	}
	for name, file := range files {
		mode := file.Mode
		if mode == 0 {
			mode = 0o644
		}
		temporary, err := os.CreateTemp(output, "."+name+"-*")
		if err != nil {
			return fmt.Errorf("creating %s: %w", name, err)
		}
		temporaryName := temporary.Name()
		removeTemporary := true
		defer func() {
			if removeTemporary {
				_ = os.Remove(temporaryName)
			}
		}()
		if err := temporary.Chmod(mode); err != nil {
			_ = temporary.Close()
			return fmt.Errorf("setting permissions on %s: %w", name, err)
		}
		if _, err := temporary.Write(file.Data); err != nil {
			_ = temporary.Close()
			return fmt.Errorf("writing %s: %w", name, err)
		}
		if err := temporary.Close(); err != nil {
			return fmt.Errorf("writing %s: %w", name, err)
		}
		if err := os.Rename(temporaryName, filepath.Join(output, name)); err != nil {
			return fmt.Errorf("replacing %s: %w", name, err)
		}
		removeTemporary = false
	}
	return nil
}

func renderKubernetesBundle(settings *config.InstallFile) (map[string]bundleFile, error) {
	if err := validateKubernetesSettings(settings); err != nil {
		return nil, err
	}
	if err := validateRenderedPackageCredentials(settings); err != nil {
		return nil, err
	}
	renderSettings, err := cloneInstallSettings(settings)
	if err != nil {
		return nil, err
	}

	// Mark which secret-backed settings are present so the object generator
	// still emits the corresponding Secret references and pull-secret links.
	// The marker values never leave memory: every Secret object is removed.
	const configured = "rendered-externally"
	registryCredentials := renderSettings.Registry.Username != ""
	packagePassword := renderSettings.Build.Packages.NeedsPassword()
	buildEnvironment := len(renderSettings.Build.Env) > 0
	builderInstructions := renderSettings.Build.Instructions != ""
	httpForwardProxy := renderSettings.Build.Proxy.HTTP != ""
	httpsForwardProxy := renderSettings.Build.Proxy.HTTPS != ""

	renderSettings.Auth.ClientSecret = configured
	renderSettings.AI.APIKey = configured
	renderSettings.Exa.APIKey = configured
	if packagePassword {
		renderSettings.Build.Packages.Password = configured
	} else {
		renderSettings.Build.Packages.Password = ""
	}
	if buildEnvironment {
		for key := range renderSettings.Build.Env {
			renderSettings.Build.Env[key] = configured
		}
	}
	if builderInstructions {
		renderSettings.Build.Instructions = configured
	}
	if httpForwardProxy {
		renderSettings.Build.Proxy.HTTP = configured
	}
	if httpsForwardProxy {
		renderSettings.Build.Proxy.HTTPS = configured
	}

	registryPassword := ""
	if registryCredentials {
		registryPassword = configured
	}
	// Naming a system namespace means the platform owns and pre-creates it;
	// this is the same contract server install follows during preflight.
	skipNamespace := settings.Kubernetes.System.Namespace != ""
	in := kubernetesSystemInput(renderSettings, skipNamespace, settings.Registry.Username, registryPassword, configured, configured)
	objects := withoutSecrets(manifests.SystemObjects(in))
	manifestYAML, err := manifests.RenderForInstallation(objects, in.Namespace)
	if err != nil {
		return nil, err
	}

	features := kubernetesSecretFeatures{
		RegistryCredentials: registryCredentials,
		PackagePassword:     packagePassword,
		BuildEnvironment:    buildEnvironment,
		BuilderInstructions: builderInstructions,
		HTTPForwardProxy:    httpForwardProxy,
		HTTPSForwardProxy:   httpsForwardProxy,
	}
	return map[string]bundleFile{
		"manifests.yaml":      {Data: []byte(manifestYAML)},
		"proxy-services.json": {Data: []byte(settings.ProxyServices.JSON()), Mode: 0o600},
		"secrets.env.example": {Data: []byte(kubernetesSecretsExample), Mode: 0o600},
		"apply.sh":            {Data: []byte(renderKubernetesApplyScript(settings, features)), Mode: 0o755},
		"README.md":           {Data: []byte(renderKubernetesReadme(settings))},
	}, nil
}

func cloneInstallSettings(settings *config.InstallFile) (*config.InstallFile, error) {
	raw, err := json.Marshal(settings)
	if err != nil {
		return nil, err
	}
	var clone config.InstallFile
	if err := json.Unmarshal(raw, &clone); err != nil {
		return nil, err
	}
	return &clone, nil
}

func validateRenderedPackageCredentials(settings *config.InstallFile) error {
	packages := settings.Build.Packages
	if packages.NeedsPassword() && packages.Password == "" {
		packages.Password = "rendered-externally"
	}
	return packages.ValidateCredentials()
}

func withoutSecrets(objects []runtime.Object) []runtime.Object {
	filtered := make([]runtime.Object, 0, len(objects))
	for _, object := range objects {
		if _, secret := object.(*corev1.Secret); secret {
			continue
		}
		filtered = append(filtered, object)
	}
	return filtered
}

