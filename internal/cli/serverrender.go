type kubernetesSecretFeatures struct {
	RegistryCredentials bool
	PackagePassword     bool
	BuildEnvironment    bool
	BuilderInstructions bool
	HTTPForwardProxy    bool
	HTTPSForwardProxy   bool
}

func renderKubernetesApplyScript(settings *config.InstallFile, features kubernetesSecretFeatures) string {
	namespace := settings.Kubernetes.SystemNamespace()
	clientID := settings.Auth.ClientID
	if clientID == "" {
		clientID = pendingOIDC
	}
	var b strings.Builder
	b.WriteString(`#!/bin/sh
set -eu

bundle_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
if [ -f "$bundle_dir/secrets.env" ]; then
  set -a
  . "$bundle_dir/secrets.env"
  set +a
fi

decode_base64() {
  if base64 --help 2>&1 | grep -q -- --decode; then base64 --decode; else base64 -D; fi
}
`)
	fmt.Fprintf(&b, "namespace=%s\n", shellQuote(namespace))
	fmt.Fprintf(&b, "system_secret=%s\n", shellQuote(manifests.SystemConfigSecretName))
	b.WriteString(`source_secret="$system_secret"
source_name=$(kubectl -n "$namespace" get secret "$source_secret" --ignore-not-found -o name)
if [ -z "$source_name" ]; then
  source_secret=donkey-system-config
  source_name=$(kubectl -n "$namespace" get secret "$source_secret" --ignore-not-found -o name)
fi
existing() {
  key="$1"
  case "$key" in
    DONKEY_REGISTRY_PASSWORD) legacy_key=registry-password ;;
    OPENAI_API_KEY) legacy_key=openai-api-key ;;
    DONKEY_OIDC_CLIENT_ID) legacy_key=oidc-client-id ;;
    DONKEY_OIDC_CLIENT_SECRET) legacy_key=oidc-client-secret ;;
    DONKEY_SESSION_KEY) legacy_key=session-key ;;
    DONKEY_TELEMETRY_KEY) legacy_key=telemetry-key ;;
    DONKEY_BUILD_ENV) legacy_key=build-env ;;
    DONKEY_BUILDER_INSTRUCTIONS) legacy_key=builder-instructions ;;
    HTTP_PROXY) legacy_key=http-proxy ;;
    HTTPS_PROXY) legacy_key=https-proxy ;;
    DONKEY_PACKAGES_PASSWORD) legacy_key=packages-password ;;
    *) legacy_key="$key" ;;
  esac
  [ -n "$source_name" ] || return 0
  encoded=$(kubectl -n "$namespace" get secret "$source_secret" -o "jsonpath={.data['$1']}") || return 1
  if [ -z "$encoded" ]; then
    encoded=$(kubectl -n "$namespace" get secret "$source_secret" -o "jsonpath={.data['$legacy_key']}") || return 1
  fi
  printf '%s' "$encoded" | decode_base64
}

registry_password="${DONKEY_REGISTRY_PASSWORD:-$(existing DONKEY_REGISTRY_PASSWORD)}"
packages_password="${DONKEY_PACKAGES_PASSWORD:-$(existing DONKEY_PACKAGES_PASSWORD)}"
oidc_client_id="${DONKEY_OIDC_CLIENT_ID:-$(existing DONKEY_OIDC_CLIENT_ID)}"
oidc_client_secret="${DONKEY_OIDC_CLIENT_SECRET:-$(existing DONKEY_OIDC_CLIENT_SECRET)}"
openai_api_key="${OPENAI_API_KEY:-$(existing OPENAI_API_KEY)}"
exa_api_key="${EXA_API_KEY:-$(existing EXA_API_KEY)}"
session_key="${DONKEY_SESSION_KEY:-$(existing DONKEY_SESSION_KEY)}"
telemetry_key="${DONKEY_TELEMETRY_KEY:-$(existing DONKEY_TELEMETRY_KEY)}"
build_env="${DONKEY_BUILD_ENV:-$(existing DONKEY_BUILD_ENV)}"
builder_instructions="${DONKEY_BUILDER_INSTRUCTIONS:-$(existing DONKEY_BUILDER_INSTRUCTIONS)}"
http_proxy="${HTTP_PROXY:-$(existing HTTP_PROXY)}"
https_proxy="${HTTPS_PROXY:-$(existing HTTPS_PROXY)}"
`)
	fmt.Fprintf(&b, "[ -n \"$oidc_client_id\" ] || oidc_client_id=%s\n", shellQuote(clientID))
	if clientID == pendingOIDC {
		b.WriteString("[ -n \"$oidc_client_secret\" ] || oidc_client_secret='pending-setup'\n")
	} else {
		b.WriteString("[ -n \"$oidc_client_secret\" ] || { echo 'DONKEY_OIDC_CLIENT_SECRET is required' >&2; exit 1; }\n")
	}
	b.WriteString("[ -n \"$openai_api_key\" ] || { echo 'OPENAI_API_KEY is required' >&2; exit 1; }\n")
	if features.RegistryCredentials {
		b.WriteString("[ -n \"$registry_password\" ] || { echo 'DONKEY_REGISTRY_PASSWORD is required' >&2; exit 1; }\n")
	}
	if features.PackagePassword {
		b.WriteString("[ -n \"$packages_password\" ] || { echo 'DONKEY_PACKAGES_PASSWORD is required' >&2; exit 1; }\n")
	}
	if features.BuildEnvironment {
		b.WriteString("[ -n \"$build_env\" ] || { echo 'DONKEY_BUILD_ENV is required because build.env is secret-backed' >&2; exit 1; }\n")
	}
	if features.BuilderInstructions {
		b.WriteString("[ -n \"$builder_instructions\" ] || { echo 'DONKEY_BUILDER_INSTRUCTIONS is required because build.instructions is secret-backed' >&2; exit 1; }\n")
	}
	if features.HTTPForwardProxy {
		b.WriteString("[ -n \"$http_proxy\" ] || { echo 'HTTP_PROXY is required because build.proxy.http is secret-backed' >&2; exit 1; }\n")
	}
	if features.HTTPSForwardProxy {
		b.WriteString("[ -n \"$https_proxy\" ] || { echo 'HTTPS_PROXY is required because build.proxy.https is secret-backed' >&2; exit 1; }\n")
	}
	b.WriteString(`if [ -z "$session_key" ]; then session_key=$(openssl rand -hex 32); fi
if [ -z "$telemetry_key" ]; then telemetry_key=$(openssl rand -hex 32); fi

`)
	if settings.Kubernetes.System.Namespace == "" {
		b.WriteString(`kubectl create namespace "$namespace" --dry-run=client -o yaml | kubectl apply -f -
`)
	}
	b.WriteString(`kubectl -n "$namespace" create secret generic "$system_secret" \
  --from-literal=DONKEY_REGISTRY_PASSWORD="$registry_password" \
  --from-literal=OPENAI_API_KEY="$openai_api_key" \
  --from-literal=EXA_API_KEY="$exa_api_key" \
  --from-literal=DONKEY_OIDC_CLIENT_ID="$oidc_client_id" \
  --from-literal=DONKEY_OIDC_CLIENT_SECRET="$oidc_client_secret" \
  --from-literal=DONKEY_SESSION_KEY="$session_key" \
  --from-literal=DONKEY_TELEMETRY_KEY="$telemetry_key" \
  --from-literal=DONKEY_BUILD_ENV="$build_env" \
  --from-literal=DONKEY_BUILDER_INSTRUCTIONS="$builder_instructions" \
  --from-literal=HTTP_PROXY="$http_proxy" \
  --from-literal=HTTPS_PROXY="$https_proxy" \
  --from-literal=DONKEY_PACKAGES_PASSWORD="$packages_password" \
  --dry-run=client -o yaml | kubectl apply -f -
`)
	if features.RegistryCredentials {
		fmt.Fprintf(&b, `kubectl -n "$namespace" create secret docker-registry %s \
  --docker-server=%s --docker-username=%s --docker-password="$registry_password" \
  --dry-run=client -o yaml | kubectl apply -f -
`, shellQuote(manifests.SystemRegistrySecretName), shellQuote(settings.Registry.Host()), shellQuote(settings.Registry.Username))
	}
	b.WriteString(`kubectl -n "$namespace" create secret generic donkey-proxy \
  --from-file=services.json="$bundle_dir/proxy-services.json" \
  --dry-run=client -o yaml | kubectl label --local -f - \
  donkey.local/installation="$namespace" donkey.local/role=proxy \
  app.kubernetes.io/managed-by=donkey app.kubernetes.io/name=donkey-proxy \
  app.kubernetes.io/part-of=donkey -o yaml | kubectl apply -f -
kubectl apply -f "$bundle_dir/manifests.yaml"
kubectl -n "$namespace" rollout restart \
  deployment/donkey-packages deployment/donkey-telemetry deployment/donkey-buildkitd \
  deployment/donkey-orchestrator deployment/donkey-server deployment/donkey-gateway deployment/donkey-ai >/dev/null

echo "Applied donkey control plane to namespace $namespace"
`)
	return b.String()
}

func renderKubernetesReadme(settings *config.InstallFile) string {
	return fmt.Sprintf(`# Donkey Kubernetes deployment

This bundle was rendered for namespace %s. The Kubernetes objects in
manifests.yaml carry the installation identity label and contain no Secret
objects or credential values.

1. Copy secrets.env.example to secrets.env and fill the values. Keep it out of
   source control. Existing Secret values are preserved when a field is empty.
2. Review manifests.yaml and proxy-services.json. The latter holds private
   target and outbound proxy URLs; keep it out of source control too.
3. Run ./apply.sh. It creates or updates the system and donkey-proxy Secrets
   and, when needed, the registry pull Secret; then it applies the manifests and rolls the pods
   which read Secret values at startup.

If an external secret manager owns credentials, create %s (and %s when the
registry is authenticated) yourself, plus donkey-proxy with services.json
containing the proxy service configuration, then apply manifests.yaml directly.
Referenced CA, Docker-config, and addon pull Secrets from the settings file
must already exist; donkey never copies their contents into this bundle.

Build values which donkey stores in its system Secret are also omitted:
DONKEY_BUILD_ENV is the JSON form of build.env, and builder instructions or
credentialed proxies use DONKEY_BUILDER_INSTRUCTIONS, HTTP_PROXY and
HTTPS_PROXY. Leave them empty when those settings are not configured.
`, settings.Kubernetes.SystemNamespace(), manifests.SystemConfigSecretName, manifests.SystemRegistrySecretName)
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}
